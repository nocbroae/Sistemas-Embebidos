from machine import I2C, Pin
import ssd1306
import framebuf


# Inicialización I2C
i2c = I2C(
    0,
    scl=Pin(22),
    sda=Pin(21),
    freq=400000
)

# Inicialización OLED
oled = ssd1306.SSD1306_I2C(128, 64, i2c)


# Logo bitmap 32x32
logo_bytes = bytearray([
    0xFF,0xFF,0xFF,0xFF,
    0xFF,0xFF,0xFF,0xFF,
    0xFF,0xFF,0xFF,0xFF,
    0xFF,0xFF,0xFF,0xFF,

    0x07,0xE0,0x07,0xE0,
    0x07,0xE0,0x07,0xE0,
    0x07,0xE0,0x07,0xE0,
    0x07,0xE0,0x07,0xE0,

    0x07,0xE0,0x07,0xE0,
    0x07,0xE0,0x07,0xE0,
    0x07,0xE0,0x07,0xE0,
    0x07,0xE0,0x07,0xE0,

    0x07,0xE0,0x07,0xE0,
    0x07,0xE0,0x07,0xE0,
    0x07,0xE0,0x07,0xE0,
    0x07,0xE0,0x07,0xE0,
])


# Crear framebuffer
logo_fb = framebuf.FrameBuffer(
    logo_bytes,
    32,
    32,
    framebuf.MONO_HLSB
)

# Mostrar imagen
oled.fill(0)

oled.blit(logo_fb, 48, 16)

oled.show()
